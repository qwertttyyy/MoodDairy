"""Ограничения частоты для тяжёлых операций приложения."""

from rest_framework.throttling import UserRateThrottle


class SnapshotRateThrottle(UserRateThrottle):
    """Отдельный лимит для выгрузки всей истории.

    Снапшот собирается только при создании ссылки врачу — операция редкая,
    но самая тяжёлая в API. Свой scope не даёт ей израсходовать общий лимит
    пользователя и одновременно ограничивает частоту полных выгрузок.
    """

    scope = "snapshot"
